func TestCleanRootStyle(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"width:198px;height:210px;background:#FFFFFF;", ""},
		{"max-width: 320.5px; background-color: white;", ""},
		{"background:#FFF;color:red", "color:red"},
		{"", ""},
	} {
		if got := cleanRootStyle(tc.in); got != tc.want {
			t.Errorf("cleanRootStyle(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
}
